/*
while loop- it is used when we don't know how many time 
the loop will iterate.
While Loop Syntax:
while(condition){
    //code to be executed 
    //increment/decrement
}
*/

public class While_Loops {
    public static void main(String[] args){
        int i = 1;
        while(i<=5){
            System.err.println(i);
            i++;
        }
    }
}
